/** 欄の中で押す文脈(カーソルが本文などの欄に在るときだけ効く物)。 */
export const IN_FIELD_CONTEXTS: ReadonlySet<KeyContext> = new Set<KeyContext>(['editor', 'append', 'row', 'live']);

/** 「操作を探す」が押せない理由の 1 文(文脈が複数なら「または」でつなぐ)。⚠ 文を組む口はここ 1 つ。 */
export function onlyWhenSentence(contexts: readonly KeyContext[]): string {
  return `${contexts.map((c) => CONTEXT_WHEN[c]).join('、または')}だけ効きます`;
}

/** 並びの順。⚠ `KEY_COMMANDS` の並びを尊重しつつ、文脈ごとに固める。 */
/**
 * ⚠ **`KeyContext` を 1 つ残らず並べる。** 抜けた文脈のコマンドは
 * `primaryContext` の既定で **`global`(「画面のどこでも」)へ落ちる** ──
 * 2026-08-18 に `filer` を足したとき実際に踏んだ:「行に焦点があるときだけ」が
 * 売りの 4 つの鍵が、設定画面で**「画面のどこでも Delete」**と名乗っていた
 * (= この面の中心的な安全主張の真逆)。全数は test が pin する。
 */
export const CONTEXT_ORDER: readonly KeyContext[] = [
  'global',
  // ⚠ `global` の隣に置く(#1042 C3)── `reading`(ノートを読んでいるとき)/
  //   `window`(別のウィンドウ)は `deselect-entry` / `close-pane` が**専用に**
  //   名乗る文脈で、足し忘れると「画面のどこでも」へ落ちる(同じ罠。上の注記)。
  'reading',
  'window',
  'filer',
  // ⚠ **`filer` の次に置く**(近い面どうしを離さない)。⚠ 足し忘れると、
  //   `dual` しか名乗らないコマンドが `primaryContext` の既定で
  //   **「画面のどこでも」の下へ落ちる**(嘘の見出し。test が全数で突き合わせる)。
  'dual',
  'editor',
  'append',
  'row',
  'live',
];

/** そのコマンドの代表文脈(並び順で一番手前にある文脈)。 */
export function primaryContext(cmd: KeyCommand): KeyContext {
  for (const c of CONTEXT_ORDER) if (cmd.contexts.includes(c)) return c;
  return 'global';
}

export interface KeyCommand {
  readonly id: string;
  /** 設定画面・ヘルプに出る名前。⚠ 変えたらマニュアルも直す。 */
  readonly label: string;
  /**
   * どの面で効くか(複数可)。
   * ⚠ **複数になる理由がある** ── 書式の近道(太字 / 斜体 / リンク)は
   * 2 列の編集欄でも 1 面の行の欄でも同じ意味で効く(`binder.ts` が既にそう書いていた)。
   * 1 つに縛ると「同じ操作が 2 つの id を持つ」ことになり、設定画面に**同じ行が 2 度**出る。
   */
  readonly contexts: readonly KeyContext[];
  /**
   * 既定の割当(複数可 = 別名)。
   *
   * ## ⚠ 「空にしない」は**無条件ではない**(2026-09-13 に読み直した。#582 段②-2)
   *
   * 🔑 この戒めの**目的**は「**user が割当を変えたとき、元へ戻せなくなる**」ことを
   *   防ぐことである(`isDefault` / 「既定に戻す」が指す先が無くなる)。
   * ⚠ だから**一度も鍵を持たない操作には、この理由が当たらない** ── 戻る先が
   *   「割当なし」なので、戻し道は失われない(設定画面は `list.length === 0` を
   *   既に「**割当なし**」として描く)。
   *
   * 🔴 **空にしてよいのは「名前で呼ぶだけの操作」である。**
   *   パレット(`palette-rows.ts`)はこの表を回して行を作るので、**鍵を要求すると
   *   「名前で呼べる」= 「鍵が割り当ててある」になり、鍵を付けられない操作
   *   (実測 151 件)が 1 つもパレットに出せない**。
   * ⚠ 空にした id は `tests/features/keymap.test.ts` の `KEYLESS` に
   *   **身元で**足すこと ── 数で縛ると、うっかり空にした物と区別が付かない。
   */
  readonly defaults: readonly string[];
  /**
   * 打っている最中(入力欄に焦点がある)でも効かせるか。既定は false。
   * ⚠ `contexts` が `editor` / `append` / `row` / `live` のものは**そもそも欄の中の話**なので
   * この項目を見ない ── 見るのは `global` だけである。
   */
  readonly whileTyping?: boolean;
  /** ヘルプに出す 1 行の説明(無ければ label だけ出す)。 */
  readonly note?: string;
  /**
   * 🔴 **押せないときの理由**(#1087 の見直し 2026-10-14)。⚠ `note` は「何をする操作か」の説明で、
   *   灰色の行に流用すると理由にならない(「前に見ていたノートへ戻ります」と言われて、なぜ押せないか分からない)。
   * 🔑 `note` 自身が「…ときだけ効きます」と条件を言っている操作には要らない。
   *   条件で押せなくなる操作のうち、`note` が条件を言っていない物だけが持つ(「操作を探す」の灰色の行が最初に引く)。
   */
  readonly whyNot?: string;
  /**
   * 🔑 **画面には出さない、探すためだけの呼び名の揺れ**(#690 I5)。
   * ⚠ 一覧の検索は `label` / `note` に加えてここも見るので、user がどの言葉で
   *   覚えていても当たる ── ただし `note` と違って**描画では読まない**ので、
   *   画面には出ない字をここへ置ける(§6.1 の名前の規則は「画面の字」が対象)。
   */
  readonly alias?: string;
  /**
   * 🔑 **この操作は「相手のノート」を選んでから実行する**という宣言(#274 段①)。
   *
   * ⚠ **字を割る解釈器の代わり**である ── 「名前 + 相手」を 1 行に打たせて割ると、
   *   名前に空白を含む操作(10 件)で成り立たない(2026-09-14 の判断)。だから
   *   **宣言のある操作だけ**、選んだ後に相手を選ぶ小窓(`pickEntryInApp`)を出す。
   *   宣言が無い操作は、今までどおり**押した瞬間に走る**。
   * ⚠ 宣言を足したら、実行する側の表(`binder.ts` の `COMMAND_WITH_ENTRY`)にも
   *   同じ id を足すこと ── 食い違いは `tests/adapter/command-list.test.ts` が全数で見る。
   * 🔴 2026-10-01 時点で**宣言のある操作は 0 件**(既存の「移す」系は、実行の中で
   *   行き先を自分で聞くので、宣言は要らなかった)。欄と配線だけ先に用意してある。
   */
  readonly needs?: 'entry';
}

