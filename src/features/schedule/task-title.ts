/**
 * 🔴 **予定の題名を、画面と書き出しに出せる素の字にする**(#1087)。
 *
 * 札の字(`TaskCard.text`)は行の字そのもの ── `**重要** [資料](entry:abc) を送る` のように
 * Markdown の記号を含む。⚠ 直す前はこれが**そのまま**札と `.ics` の `SUMMARY` に出ていた
 * (外の予定表では `**` も `entry:abc` も意味を持たない)。
 *
 * 🔑 **書き換えには使わない** ── 行を書き換える口は札の `rawLine`(原文の行)を使う。
 *   この関数が返すのは**見せる字**であって、本文へ戻す字ではない。
 * ⚠ 札の `text` 自体は変えない(繰り返しの回の突き合わせ `repeatMateKey` と、連絡先の読みが
 *   その字を使う)── 見せる所でだけ通す。
 *
 * ⚠ pure module。落とすのは inline の記号だけで、**字は 1 つも足さない / 言い換えない**。
 */

/** `:role:[X]{attrs}` ── 中身だけ残す(`strip-dialect.ts` が読む方言)。 */
const DIALECT_ROLE = /:[a-z]+:\[([^\]]*)\](?:\{[^}]*\})?/g;

/**
 * 素の字にする。
 * - 画像 `![alt](url)` → alt / リンク `[label](url)` → label
 * - 強調 `**x**` `*x*` / 取り消し `~~x~~` / コード `` `x` `` → 中身
 * - `:role:[x]{…}` → x
 * ⚠ 記号が釣り合っていないもの(`2*3` など)は触らない ── 字を黙って欠かない。
 */
export function plainTaskTitle(text: string): string {
  let s = text;
  s = s.replace(/!\[([^\]]*)\]\([^)\s]*(?:\s+"[^"]*")?\)/g, '$1');
  s = s.replace(/\[([^\]]+)\]\([^)\s]*(?:\s+"[^"]*")?\)/g, '$1');
  s = s.replace(DIALECT_ROLE, '$1');
  s = s.replace(/`([^`]+)`/g, '$1');
  s = s.replace(/\*\*(?!\s)([^*]+?)(?<!\s)\*\*/g, '$1');
  s = s.replace(/~~(?!\s)([^~]+?)(?<!\s)~~/g, '$1');
  s = s.replace(/(^|[^*\w])\*(?![\s*])([^*]+?)(?<![\s*])\*(?![*\w])/g, '$1$2');
  return s;
}
