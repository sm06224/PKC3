/**
 * 🔴 **人が読む「大きさ」は、この 1 本だけが作る**(#454)。
 *
 * ## 何が起きていたか
 *
 * 同じ添付の大きさが、見る画面によって `2KB` と `2.0 KB` に分かれていた。
 * ⚠ 実装を数えたら **4 本**あった(#454 の本文は 3 本と書いているが、
 *   `adapter/ui/render/detail.ts` の `formatSize` を数えていなかった)。
 *   さらに **MB だけを自前で綴る場所が 3 か所**あり、合わせて 7 か所が
 *   同じ量を別々の形で出していた。
 *
 * ## 寄せ先は `512 B` / `2.0 KB` / `2.0 MB`
 *
 * ① 4 本のうち **2 本が既にこの形**(`storage-profile` / `detail`)で、
 *    画面としても**添付の説明・容量の一覧・削除の確認**の 3 面がこちら側
 * ② 数と単位の間に空白を置くのが通例である
 * ③ ⚠ もう一方(`2KB`)は **KB を整数へ丸め、MB だけ小数 1 桁**で、
 *    **同じ関数の中で精度が変わっていた**
 *
 * ## ⚠ 丸めてから単位を決める
 *
 * 先に単位を決めると、**`1024.0 KB` が出る**(1.0 MB と書くべき所)── 割った値を
 * 1 桁へ丸めた**あと**に 1024 と比べる。実測(境目は 1 バイトで切り替わる):
 * `1048524` は**どちらでも** `1023.9 KB`、`1048525` は素直に書くと `1024.0 KB` /
 * この形なら `1.0 MB`。
 *
 * ⚠ **pure module**。⚠ 桁を揃えるより**読めること**を優先する
 * (一覧でも右揃えにはしていない ── 揃えるなら CSS の仕事である)。
 */

/** 小数 1 桁へ丸める。⚠ **単位を決める前に**通す(上の docstring)。 */
const round1 = (x: number): number => Math.round(x * 10) / 10;

export function humanBytes(n: number): string {
  if (n < 1024) return `${n} B`;
  const kb = round1(n / 1024);
  if (kb < 1024) return `${kb.toFixed(1)} KB`;
  return `${round1(n / (1024 * 1024)).toFixed(1)} MB`;
}
