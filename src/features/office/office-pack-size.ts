/**
 * 🔴 **Office 一式の大きさを、user に見せる形で 1 か所に持つ**(#702、2026-09-08)。
 *
 * ## 何が起きていたか
 *
 * 画面には「**約 77MB** の一式をこの端末に入れます」と出ていたが、
 * **実際に取りに行くのは約 93MB** だった ── 空きが 80MB の人は、その字を信じて押し、
 * 途中で失敗する。⚠ しかも**失敗の理由もまた「約 77MB 必要です」**と出ていたので、
 * 「77MB 空いているのに失敗した」という、原因の分からない形になっていた。
 *
 * ## 🔴 77MB は「2 本だけ」の合計だった
 *
 * | 何 | 量 |
 * |---|---|
 * | `soffice.wasm.gz` + `soffice.data.gz` | 約 **77MB** ← 画面に出ていた数字 |
 * | ＋ `soffice.js` / `qtloader.js` / `soffice.data.js.metadata` / フォント | |
 * | **目録(`pack.json`)が指すものの合計** | 約 **93MB** ← 実際に取る量 |
 *
 * 実測は `build/office-wasm/make-pages-bundle.mjs` のコメントに残っている ──
 * 「宣言 **97,311,959** に対し実際に入るのは **97,305,931**」(2026-08-14、実機検証)。
 * 97,305,931 バイト ≒ **92.8 MB**。
 *
 * ## 🔑 正本は目録の `totalBytes` である
 *
 * ⚠ この定数は**目録を読む前に出す概算**にすぎない ── 設置が済んだ後の面は
 * `humanBytes(meta.totalBytes)` で**実数**を出す(`office-pack-panel.ts`)。
 * 🔑 だから**近い側ではなく大きい側へ寄せる** ── 少なく言って失敗させるより、
 * 多めに言って「思ったより少なかった」ほうが user は損をしない。
 *
 * ⚠ **pure module**。DOM も storage も知らない。
 */

/**
 * 一式を取るのに要る量(MB、概算)。⚠ **目録が指すものの合計**であって、
 * 圧縮された本体 2 本だけの量ではない。
 */
export const OFFICE_PACK_APPROX_MB = 93;

