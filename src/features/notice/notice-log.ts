/**
 * 🔴 **お知らせの登記表**(P11 段⑤。user 指示 2026-08-07)。
 *
 * > 「**PKC3 にも PKC2 のようにお知らせポップアップをつけてください /
 * > お知らせ掲載内容は過去のお知らせとして、最大 10 件を…ヘルプ画面から
 * > 参照できるようにしてください**」
 *
 * ## PKC2 の失敗を繰り返さない(実測で確かめた 9 件のうち、ここに効く分)
 *
 * | PKC2 で起きたこと | ここでの対処 |
 * |---|---|
 * | 6 件あるのに**先頭 1 件しか読まれず**、残りを毎ビルド配っていた | **過去の一覧**を持ち、`recentNotices` が読む。読まれない entry を作らない |
 * | `date` field を宣言して**一度も読まなかった** | **field を持たない**。日付は id から引く(`noticeDate`)── 二重表現にしない |
 * | `textContent` で描くのに本文が `**強調**` で書かれ、**アスタリスクが見えていた** | **素のテキストと決める**。記法を書いたら test が落とす |
 * | 1 entry 22 項目・1 項目 200 字超の壁ができた | **上限を数で持つ**(件数・項目数・字数)。散文の規律にしない |
 * | 表示上限が複数箇所に散る | **切るのは `recentNotices` 1 か所だけ** |
 *
 * ⚠ **pure module**。browser API を使わない(既読は adapter 側が持つ)。
 */

/** お知らせ 1 件。⚠ **日付の field を持たない**(id が持っている)。 */
export interface Notice {
  /**
   * `YYYY-MM-DD-slug`。⚠ **既読の鍵**であり、**並び順の鍵**でもある。
   * 日付が前置きなので、文字列の降順がそのまま新しい順になる。
   */
  readonly id: string;
  readonly title: string;
  /** 本文。⚠ **素のテキスト**(markdown 記法を書かない ── 描画は textContent)。 */
  readonly items: readonly string[];
}

/**
 * 🔴 **ヘルプ画面に出す件数**(user 裁定 2026-08-07 Q1)。
 * ⚠ **切るのはここ 1 か所**。面ごとに `slice` を書くと、帯とヘルプで件数が食い違う。
 */
export const NOTICE_SHOW_MAX = 10;

/**
 * 🔴 **登記表に残す件数の上限**(裁定 Q1)。
 * 🔴 **表示上限と同じ数にする**(2026-08-29)。⚠ 直す前は **2 倍(20)**で、理由は
 *   「**原本は残す**」だった ── ところが**その役目はいま `CHANGELOG.md` が担っている**
 *   (2026-08-18 から)ので、11 件目より後ろは**原本でもなく画面にも出ない、
 *   配るだけの重り**になっていた(実測 10 件)。
 * 🔑 揃えると不変条件が 1 つ増える:**登記表 = 画面に出るもの**。
 *   ⚠ user から見える所は **1px も変わらない**(その 10 件はもともと出ていない)。
 *   落ちた分は今までどおり `CHANGELOG.md` が受ける。
 */
export const NOTICE_KEEP_MAX = 10;

/**
 * 🔴 **既読の集合に残す id の件数**(`adapter/platform/notice-store.ts`)。
 *
 * ⚠ **登記表の上限とは別物である。** 2026-08-29 まで `NOTICE_KEEP_MAX` を使い回して
 *   いたが、登記表を 20 → 10 へ下げた瞬間に**読んだお知らせが毎起動よみがえる**
 *   ところだった(着地前レビューが拾った。再現は
 *   `tests/adapter/notice-store.test.ts`「登記表から落ちた id が…」)。
 *
 * ## なぜ表示件数より大きくないといけないか
 *
 * 既読の集合には**登記表から落ちた id も残る**(user はそれを読んだので)。
 * だから必要な席は「いま出る 10 件」+「落ちた id のうち user が読んだ分」であり、
 * 表示件数と同じにすると**落ちた id が生きている id を押し出す**。
 * 押し出された 1 件は未読へ戻り、閉じても `same` 判定で書込が起きないので
 * **同じ 1 件が毎起動出続ける**(localStorage を消すまで止まらない)。
 *
 * 🔑 席の数だけに頼らず、`markSeen` は**登記表に在る id を先に残す**
 *   ── 席が足りなくなる形そのものを消してある(CLAUDE.md
 *   「衝突は、検出するより起こらなくするほうが強い」)。ここは**余裕**である。
 */
export const NOTICE_SEEN_MAX = NOTICE_SHOW_MAX * 2;

/** 1 entry の項目数の上限(PKC2 は 22 項目の壁ができた)。 */
export const NOTICE_ITEMS_MAX = 6;
/** 1 項目の字数(下限も置く ── 空の行が user に出るのを止める)。 */
export const NOTICE_ITEM_CHARS_MAX = 120;
export const NOTICE_ITEM_CHARS_MIN = 4;

/**
 * 🔴 **新しい順に並べて、上限まで切る**。
 * ⚠ **ここだけが切る**(上の `NOTICE_SHOW_MAX` の注記)。
 *
 * 🔴 **同じ日のものは、登記表に書いた順で出す**(2026-08-29 の動線レビュー 欠陥 5)。
 * ⚠ 直す前は **id 全体**で比べていたので、日付が同じ 14 件は
 *   **英語スラッグの綴り順**で並んでいた ── いちばん実害の大きい知らせ
 *   (「押しても何も起きなかったのが直った」)が **7 番目**に回り、
 *   user は「次へ」を **6 回**押さないと読めなかった。
 * 🔑 日付だけで比べれば、`Array.sort` は**安定**なので配列の順が残る
 *   ── 登記表は**先頭に足す**規約(`notice-writing` skill)なので、それが「新しい順」である。
 */
export function recentNotices(
  all: readonly Notice[],
  limit = NOTICE_SHOW_MAX,
): readonly Notice[] {
  return [...all]
    .sort((a, b) => {
      const [x, y] = [noticeDate(a.id), noticeDate(b.id)];
      return x < y ? 1 : x > y ? -1 : 0;
    })
    .slice(0, limit);
}

/**
 * まだ見ていないものを新しい順に返す。
 * ⚠ 既読は **id の集合**で渡す ── 「最後に閉じた 1 件」と比べると、
 *   旧ビルドへ戻ったときに**既読が巻き戻る**(PKC2 の F5)。
 */
export function unreadNotices(
  all: readonly Notice[],
  seen: readonly string[],
): readonly Notice[] {
  const seenSet = new Set(seen);
  return recentNotices(all).filter((n) => !seenSet.has(n.id));
}

/** id の先頭から日付を取り出す(`YYYY-MM-DD-slug` → `YYYY-MM-DD`)。 */
export function noticeDate(id: string): string {
  return /^(\d{4}-\d{2}-\d{2})/.exec(id)?.[1] ?? '';
}

