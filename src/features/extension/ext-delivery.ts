/**
 * 🔴 **user のジェスチャで、実体を 1 件だけ拡張へ渡す**(#195 / C-5 段②)。
 *
 * 設計は `docs/development/pkc-extension-host-design-2026-08.md`。
 *
 * ## 段① との違いは「本文が乗る」ことだけではない ── **誰が始めるか**が違う
 *
 * | | 段①(見取り図) | 段②(実体) |
 * |---|---|---|
 * | 中身 | 題名・種類・日付・印 | それ + **本文** |
 * | 始める人 | ホスト(一覧が変わったら押し出す) | 🔴 **user**(情報ペインで押す) |
 * | 何件 | 全部(上限 5000) | 🔴 **押した 1 件だけ** |
 *
 * 🚫 **拡張から取りに行く口は作らない**(pull 経路 MUST NOT)。
 * ⚠ 「`get` を 1 つ足すだけ」に見えるが、それを足した瞬間に
 *   **拡張が好きなときに好きな本文を読める**ようになる ── user のジェスチャは
 *   「この 1 件を見せる」であって「以後ぜんぶ読んでよい」ではない。
 * 🔑 だから `ext-wire.ts` の `parseExtRequest` は段② でも **`hello` しか受けない**。
 *
 * ## ⚠ 渡らないもの(名指しで書く ── 「書いていない = 渡らない」にしない)
 *
 * - **添付の bytes** … 本文に `asset:` の参照が残るが、拡張はそれを解決できない。
 *   ⚠ これは欠陥ではなく**段② の範囲**である(bytes を渡すのは別の判断が要る ──
 *   見せた覚えのない画像が拡張の手に渡る)。拡張の作者に分かるよう
 *   `assetRefs` に**参照の数だけ**を添える(中身も key も渡さない)。
 * - **履歴・関係・タグの一覧** … 段② は「いま画面で選んでいる 1 件」である。
 *
 * ## 🔑 本文に上限を置かない ── その理由
 *
 * 見取り図には上限(`EXT_PROJECTION_MAX`)が在るのに、こちらには置かない。
 * ⚠ 一貫していないように見えるので、理由を書く:
 *
 * - 見取り図は **ホストが勝手に押し出す**ので、10 万件の窓で 10 万行を渡す
 *   理由が無い ── 上限は「頼んでいないのに大量に渡さない」ための門である
 * - 実体は **user が 1 件を選んで押した結果**である。そこで本文を切ると、
 *   user が「渡した」と思った物と、拡張が受け取った物が**食い違う** ──
 *   🔴 それは黙って壊れる側であり、`truncated` を付けても
 *   **user の画面には出ない**(拡張の中でしか見えない)
 * - 本文は PKC-Markdown の**文字列**である(bytes は添付として別に居る)ので、
 *   人が書いた量で上がる。⚠ 「重いから切る」は判断理由にしてはならない
 *   (不可侵指示 2026-08-03「配る量は気にしない。効くのは定常」)
 *
 * ⚠ **覆る条件**: 実測で「大きな本文を渡すと窓が固まる」と**測って**分かったとき。
 *   そのときも切るのではなく、**押す前に user へ言う**(切るのは最後の手段)。
 *
 * 🔑 **pure module**。窓も DOM も storage も知らない。
 */
import { extEntryOf, type ExtEntry } from './ext-projection';
import type { EntryMeta } from '@core/model/entry-meta';

/**
 * 本文の中の添付参照を数える正規表現。
 *
 * ⚠ **判定を 2 つ目に生やさない** ── 「どれが添付参照か」の正本は
 *   `features/asset/asset-ref-scan.ts` である。ここが要るのは**数だけ**なので
 *   同じ規則を写さず、⚠ **緩く(false-keep 側に)数える**:
 *   多めに出ても「参照が在るかもしれない」と読めるだけで、
 *   **少なく出ると「無い」と誤解させる**(そちらが害である)。
 * 🔑 だから名前も `approx`(おおよそ)にしてある ── 呼び側が精度を誤解しないため。
 */
const ASSET_REF = /asset:[A-Za-z0-9._-]+/g;

/** 拡張へ渡す実体 1 件。⚠ **写す列を名指しする**(段① と同じ門)。 */
export interface ExtDeliveredEntry extends ExtEntry {
  /** 🔴 本文(PKC-Markdown の原文)。⚠ 切らない ── 上の「上限を置かない理由」。 */
  readonly body: string;
  /**
   * 本文が参照している添付の**おおよその数**。⚠ **key も bytes も渡さない**。
   * 🔑 これが 0 でないとき、拡張は「見えていない物がある」と分かる ──
   *   無いと、拡張の作者は**本文が壊れている**と読む。
   */
  readonly assetRefsApprox: number;
}

/**
 * `EntryMeta` と本文から、渡す 1 件を組む。⚠ **口はここ 1 つ**(§7)。
 *
 * ⚠ 段① の列は `extEntryOf` を**呼んで**作る ── 写し直すと、
 *   段① に列を足した日に**こちらだけ古くなる**(同じ問いに答える口が 2 つ)。
 */
export function deliveredEntryOf(meta: EntryMeta, body: string): ExtDeliveredEntry {
  return {
    ...extEntryOf(meta),
    body,
    assetRefsApprox: (body.match(ASSET_REF) ?? []).length,
  };
}
