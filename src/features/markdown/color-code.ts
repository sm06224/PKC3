/** 見本を出す形(3 / 6 / 8 桁の 16 進、大文字小文字は問わない)。 */
const COLOR_CODE = /^#(?:[0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})$/;

/** インラインコードの中身が、見本を出す色コードか。 */
export function isColorCode(content: string): boolean {
  return COLOR_CODE.test(content);
}
