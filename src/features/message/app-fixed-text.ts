const TAILS_LONGEST_FIRST = [...APP_FIXED_TAILS].sort((a, b) => b.length - a.length);

/** `MessagePost.post` へそのまま足せる形(空の物は持たない ── 渡す先の既定のまま)。 */
export interface AppFixedParts {
  readonly fixedHead?: string;
  readonly fixedTail?: string;
}

/**
 * 🔴 **この字のうち、伏せずに通すアプリの固定の部分**(#2084)。判定はここ 1 か所
 * (`showStatus` の積み口 `status-notice.ts` と、`OP_NOTICE` / `OP_FAILED` の積み口 `main.ts` が同じ関数を呼ぶ)。
 */
export function fixedPartsOfAppText(text: string): AppFixedParts {
  if (APP_FIXED_TEXTS.includes(text)) return { fixedHead: text };
  const tail = TAILS_LONGEST_FIRST.find((t) => text.endsWith(t));
  return tail === undefined ? {} : { fixedTail: tail };
}
