/**
 * 🔴 **メッセージへ積む知らせのうち、アプリ自身が書いた固定の字の表**(#2084)。
 *
 * ## 何を直したか
 *
 * メッセージ(簡易履歴・システムのメッセージ)へ積む字は、user の題名・ファイル名を漏らさないよう
 * `sanitizeMessageText` が「」の中身を「…」に伏せる(#1087)。⚠ その規則は**PKC3 自身のボタン名**
 * (「書き出す ▾」「差分を書き出す」「名前を直す」…)まで伏せていたので、
 * 「コレクションの「…」に「…」が出ます」のように意味の通らない記録が残っていた。
 *
 * ## どう通すか
 *
 * この表に**字のまま**載せた固定の文だけを通す ── 文全体(`APP_FIXED_TEXTS`)か、文の終わり
 * (`APP_FIXED_TAILS`。user の字が前に来て、案内のボタン名が後ろに来る文)。
 * 🔑 通るのは**表に書いた字そのもの**だけである ── user の字がたまたま同じ字で終わっていても、
 *   見えるのはアプリの固定の字で、user の字の残りは今までどおり伏せる。だから表は漏れの穴にならない。
 * ⚠ 字は各所の知らせの字と**1 字も違わない**こと(`tests/features/app-fixed-text.test.ts` が src と突き合わせる)。
 *   知らせの字を書き換えたら、ここも直す(直さないと、その文のボタン名がまた「…」になる)。
 * ⚠ user の字(題名・ファイル名・検索名・タグ名・フォルダ名)は**ここへ入れない**。
 */

