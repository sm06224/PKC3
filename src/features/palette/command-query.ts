/**
 * 左の列の「探す」欄に **`>` を先頭に打つと、操作を探す**(#274 段①。姿 = D)。
 * **pure module**。
 *
 * ## 🔑 判定をここ 1 か所に置く
 *
 * この欄の字は 3 か所が読む ── ①一覧を操作に替える(描画)②本文の検索を撃つか
 * (`reducer`)③検索語の記録に積むか(`search-log`)。**3 か所が別々に「先頭が `>`」を
 * 書くと、片方だけ全角を拾わない日が来る**(§7)ので、読み口はこの関数 1 つにする。
 *
 * ## 🔴 全角の `＞` も同じに扱う
 *
 * ⚠ 日本語入力のまま打つと `>` は **`＞`(全角)** になる(#764 の「打ち方の次元」)。
 *   半角だけ拾うと、**日本語で書く user が操作の一覧に入れない**。
 *
 * ## 🔴 「打った字を名前と相手に割る」ことはしない
 *
 * `>` の後ろは**探し語そのもの**(`paletteRows` にそのまま渡す)。⚠ 操作の名前は
 * 空白を含むものが在る(10 件)ので、空白で「名前 + 相手」へ割る解釈器は成り立たない
 * (2026-09-14 の判断)。相手が要る操作は `KeyCommand.needs` の宣言で、選んだ後に聞く。
 */

/** 操作を探す印。⚠ 全角も(上の注記)。 */
export const COMMAND_PREFIXES: readonly string[] = ['>', '＞'];

/**
 * 欄の字が「操作を探す」なら、**印を除いた探し語**を返す。そうでなければ `null`。
 *
 * ⚠ 先頭が印のときだけ(途中の `>` は検索語である ── `a > b` を探す人が居る)。
 * ⚠ 空白は削らない(`paletteRows` が自分で削る ── 判定を 2 つにしない)。
 */
export function commandQueryOf(filter: string): string | null {
  for (const p of COMMAND_PREFIXES) {
    if (filter.startsWith(p)) return filter.slice(p.length);
  }
  return null;
}
