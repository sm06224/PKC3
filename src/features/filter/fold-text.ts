/**
 * 🔴 **字を比べるときだけ揃える、唯一の関数**(台帳 #1852 の束 B1、依頼 173・195・258・276・335)。
 *
 * user の物語: 題名の絞り込みで「abc」と打っても「ＡＢＣ報告」が出ない。Mac のファイル名から写した
 * 「が」(か + 濁点の 2 字)は、普通に打った「が」で探しても出ない。タグも、見た目が同じ「が」が
 * 2 つの別のタグとして数えられる。
 *
 * ## 揃えるもの / 揃えないもの
 *
 * | 揃える | 例 |
 * |---|---|
 * | 全角と半角 | 「ＡＢＣ」=「ABC」/「１２」=「12」 |
 * | 半角カナと全角カナ | 「ﾊﾝｶｸ」=「ハンカク」 |
 * | 濁点の持ち方(結合文字と合成済み) | 「か」+「゛」=「が」 |
 * | 大文字と小文字 | 「ABC」=「abc」 |
 *
 * ⚠ **ひらがなとカタカナは揃えない**(「りんご」と「リンゴ」は別の字のまま)── 意味を分けて使うことが
 *   あるため(依頼 258 の A。Gemini の回答で 195・276・335 も同じ扱いに統一)。
 *   「操作を探す」(`palette-rows.ts`)はこの 2 つも潰すが、あちらは操作名を当てる別の道具である。
 *
 * ⚠ **比べるときだけ揃える。保存されているノートの字は 1 字も変えない**(返すのは比較用の字で、
 *   書き戻す口にはつながない)。
 * 🔑 題名の絞り込み(`title-filter.ts`)とタグの突き合わせ(`flavor/tags.ts`)に加え、**本文の全文検索の索引と問い合わせ**
 *   (台帳 #1852 の束 B2、依頼 258・335・115-2)も**どれもここを通る**(§7 ── 同じ判定を 2 か所に書かない)。
 *   索引へ入れる字は `foldWidth`(大小は FTS5 の trigram が畳む)、題名・タグ・画面側の比べは `foldText`。
 */
export function foldWidth(s: string): string {
  return s.normalize('NFKC');
}

export function foldText(s: string): string {
  return foldWidth(s).toLowerCase();
}

/**
 * 🔴 **空白で区切った語に割る**(台帳 #1852 の束 B2、依頼 194・260・115-1)。全角の空白(U+3000)も区切り ──
 * `foldWidth` が半角へ揃えるので `\s` だけで足りる。空の語は落とす。引用符・`-` は読まない(左の列の欄は打った字のまま)。
 */
export function splitWords(s: string): string[] {
  return foldWidth(s)
    .split(/\s+/)
    .filter((w) => w !== '');
}
