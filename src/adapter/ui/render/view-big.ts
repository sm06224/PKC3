/**
 * 🔴 **押すと別の窓で大きく見られる印**(#527)── 印を付ける判定を **1 か所**に置く。
 *
 * ## なぜ file を分けたか
 *
 * 2026-08-28 の 1 稿目は、この判定を `mermaid-hydrate.ts` の中に直接書いていた。
 * ⚠ そこへ**本文に貼った画像**(`img[data-pkc-asset-key]`)を足すと、
 * **同じ判定が 2 か所**になる(CLAUDE.md §7)── 片方だけ直すと
 * 「図は編集中に原文が開くのに、画像は窓が開く」という**面ごとに違う動き**になる。
 *
 * ## 判定は 1 つ ── **読む面か**
 *
 * | 面 | 絵を押すと |
 * |---|---|
 * | **読む面** | 別の窓で**大きく見る**(この印を付ける) |
 * | **1 面の編集**(`editor-live`) | **その行の原文**が開く(印を付けない) |
 *
 * 🔴 **編集の面で付けてはいけない**(2026-08-28、実ブラウザで測って判明)。
 * 付けたまま測ったら**窓が開いて行は開かなかった** ── つまり
 * **図の原文を直す道を丸ごと奪っていた**。
 *
 * ⚠ **印・カーソル・吹き出し・キーボードの止まり先はまとめて付ける** ── 片方だけ付けると
 * 「押せそうに見えるのに押せない」ができる。
 */

/** 押し所であることを示す属性(`binder.ts` の `view-big` が受ける)。 */
export const VIEW_BIG_ACTION = 'view-big';

/**
 * 吹き出しの字。⚠ **何が起きるか**を書く(その場拡大と別窓切出)。
 * 🔑 **1 か所で持つ** ── 図と画像で違う字が出ると、user は**別の機能だ**と読む。
 */
// ⚠「ポップアップ」は、ほかの所では「ブラウザが止めるウィンドウ」の意味で使っている ── ここでは使わない(#1087)
export const VIEW_BIG_TITLE = '押すと大きく表示します(右上の ⧉ で別のウィンドウに開けます)';

/**
 * 読む面に居る絵に、押し所の印を付ける。編集の面では**何もしない**。
 *
 * @param img 印を付ける `<img>`(既に画面の木に繋がっていること ── 面の判定に要る)
 */
export function markViewBig(img: HTMLImageElement): void {
  // ⚠ **繋がっていないと面が読めない** ── `closest` が常に `null` を返すので、
  //   編集の面の絵にも印が付いてしまう(「読む面だから付いた」と見分けがつかない)
  if (!img.isConnected) return;
  if (img.closest('[data-pkc-region="editor-live"]') !== null) return;
  img.setAttribute('data-pkc-action', VIEW_BIG_ACTION);
  img.style.cursor = 'zoom-in';
  img.title = VIEW_BIG_TITLE;
  /**
   * 🔴 **キーボードだけでも大きく表示できる**(台帳 #1852 束 U1 残り、依頼 79-3 C。Gemini 回答 = 推薦どおり)。
   * ⚠ 直す前は画像を押すしか開く道が無く、Tab で画像に止まれなかった(マウスを使えない人は開けない)。
   * 🔑 `tabindex="0"` + `data-pkc-action` の要素は、Enter / Space で同じ action を撃つ既存の道に乗る
   *   (`binder.ts` の `onKeydown`)── 受け手を増やさない。止まった画像の枠は `app.css` の `:focus-visible`。
   * ⚠ 印を付ける条件は上の「読む面か」と同じ 1 本のまま(編集の面では付かない = Tab の止まり先も増えない)。
   */
  img.tabIndex = 0;
  img.setAttribute('role', 'button');
}
