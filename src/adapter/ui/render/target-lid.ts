/**
 * 🔴 **その口が効く先の lid を、押した要素に持たせる**(#770 段② / #848、2026-09-13)。
 *
 * ## なぜ要るか
 *
 * 本文の面は **2 通りの出方**をする:
 *
 * | | 何を出すか |
 * |---|---|
 * | 主の枠 | **いま選んでいる**ノート(`selectedLid`) |
 * | 🔴 留めた枠(横に並べた枠) | **選択と関係なく「その 1 件」** |
 *
 * ⚠ だから留めた枠に置いた口が `selectedLid` へ撃つと、**押していないノートが
 * 書き換わる**。2026-09-12 に実際にそうなっていた(添付の設定 4 つ + 起動 3 本)。
 *
 * 🔑 **検算は 1 つ:「この面で押したとき、効く先は何で決まるか」を口ごとに言えるか。**
 * 「`selectedLid`」と答えた口が、**選択と無関係に描かれる面**に在るなら事故である。
 *
 * ## ⚠ 名前を `launch` から変えた理由
 *
 * 2026-09-12 の 1 稿目は `data-pkc-launch-lid` だった ── **起動の 3 本**にしか
 * 付けていなかったので、そのときは正しい名前だった。⚠ いまは**設定の口**も
 * 同じ仕組みに乗るので、「起動」と名乗る属性を設定が読むことになる。
 * 🔑 **取れない先を配布と呼ぶと、次に読む人も同じ読み違えをする**(CLAUDE.md)──
 * 効く先を表す 1 つの名前にした。
 */

/** 押した要素が「効く先」を持つときの属性名。⚠ 綴りを 2 か所に書かない。 */
export const TARGET_LID_ATTR = 'data-pkc-target-lid';

/**
 * `el` に効く先を持たせて、そのまま返す(組み立ての途中に挟める形)。
 * ⚠ 空の lid は付けない ── 付けると受け手が「属性が在る = 効く先が決まっている」と
 *   読んで、`selectedLid` への落とし方を飛ばす。
 */
export function markTargetLid<T extends Element>(el: T, lid: string): T {
  if (lid !== '') el.setAttribute(TARGET_LID_ATTR, lid);
  return el;
}
