/**
 * 🔴 **本文の電話番号を押せるようにする判定**(#278 段②)。
 *
 * ⚠ この test がいちばん見ているのは「**拾わないこと**」である ──
 * 日付や版番号を電話にすると、**本文が化ける**(押せる字が勝手に生える)。
 * 🔑 だから拾う側と拾わない側を**対で**並べる。
 */
import { describe, expect, it } from 'vitest';
import { findPhones, telOf } from '../../src/features/contact/phone-link';

describe('電話番号として通る形(#278 段②)', () => {
  it('🔴 国内の 10 桁・11 桁を拾う', () => {
    expect(telOf('090-1234-5678')).toBe('09012345678');
    expect(telOf('03-1234-5678')).toBe('0312345678');
    expect(telOf('0120-123-456')).toBe('0120123456');
    // ⚠ 区切りなしでも拾う(名刺から写した形)
    expect(telOf('09012345678')).toBe('09012345678');
  });

  /**
   * 🔴 **日本語入力のまま打った形を、fixture に必ず持つ**(CLAUDE.md §2 の #764)。
   * ⚠ ASCII だけの corpus は、**日本語で書く user の経路を 1 度も通らない**。
   */
  it('🔴 全角で打った番号も拾い、tel は半角にする', () => {
    expect(telOf('０９０－１２３４－５６７８')).toBe('09012345678');
    expect(telOf('＋８１－９０－１２３４－５６７８')).toBe('+819012345678');
  });

  it('🔴 国番号つきは 8〜15 桁', () => {
    expect(telOf('+81-90-1234-5678')).toBe('+819012345678');
    expect(telOf('+1-202-555-0173')).toBe('+12025550173');
    expect(telOf('+1-234'), '短すぎるものを通した').toBeNull();
    expect(telOf('+1234567890123456'), '長すぎるものを通した').toBeNull();
  });

  it('🔴 番号でないものは通さない', () => {
    // 🔴 これがいちばん大事 ── 日付を電話にしたら本文が化ける
    expect(telOf('2026-09-09'), '日付を電話にした').toBeNull();
    /**
     * 🔴 **桁が足りているのに 0 で始まらないもの**(変異試験 P1 が SURVIVED で教えた)。
     * ⚠ 直す前の corpus は日付(8 桁)しか持っていなかったので、
     *   **「先頭が 0」の門を外しても桁数の門が救っていた** ── 門を 2 つ置いたら、
     *   **その門だけが鳴る場面**が要る(CLAUDE.md §1)。
     */
    expect(telOf('1234-5678-90'), '10 桁の注文番号を電話にした').toBeNull();
    expect(telOf('9012-3456-789'), '11 桁の会員番号を電話にした').toBeNull();
    expect(telOf('1-2-3'), '章番号を電話にした').toBeNull();
    expect(telOf('123-4567'), '郵便番号を電話にした').toBeNull();
    expect(telOf('0120-123'), '桁が足りないものを通した').toBeNull();
    expect(telOf('090-1234-56789'), '桁が多いものを通した').toBeNull();
    expect(telOf('090--1234-5678'), '区切りが連続する形を通した').toBeNull();
    expect(telOf('-090-1234-5678'), '区切りで始まる形を通した').toBeNull();
    expect(telOf('090-1234-5678-'), '区切りで終わる形を通した').toBeNull();
  });
});

describe('本文の中から拾う(#278 段②)', () => {
  it('🔴 前後に字が在っても、番号だけを切り出す', () => {
    const hits = findPhones('連絡は 090-1234-5678 まで。');
    expect(hits).toHaveLength(1);
    expect(hits[0]!.raw).toBe('090-1234-5678');
    expect(hits[0]!.tel).toBe('09012345678');
    // ⚠ 添字は元の字に対して正しいこと(ここがずれると本文が壊れる)
    expect('連絡は 090-1234-5678 まで。'.slice(hits[0]!.start, hits[0]!.end)).toBe(
      '090-1234-5678',
    );
  });

  it('🔴 日付が混じっていても、日付は拾わない', () => {
    const hits = findPhones('2026-09-09 に 090-1234-5678 へ掛ける');
    expect(hits.map((h) => h.raw), '日付まで拾った').toEqual(['090-1234-5678']);
  });

  it('🔴 番号の一部を切り出さない(前が数字・区切りなら頭ではない)', () => {
    // ⚠ 直す前の素朴な走査は、ここで `090-1234-5678` を切り出していた
    expect(findPhones('2026-090-1234-5678'), '番号の途中から拾った').toEqual([]);
    expect(findPhones('x090-1234-5678'), '英字の後ろから拾った').toEqual([]);
  });

  it('⚠ メール・型番の中は拾わない', () => {
    expect(findPhones('090-1234-5678@example.com'), 'メールの一部を拾った').toEqual([]);
    expect(findPhones('0120-123-456a'), '型番の一部を拾った').toEqual([]);
  });

  it('🔴 2 件在れば 2 件とも拾い、重ならない', () => {
    const s = '会社 03-1234-5678 / 携帯 ０９０－１２３４－５６７８';
    const hits = findPhones(s);
    expect(hits.map((h) => h.tel)).toEqual(['0312345678', '09012345678']);
    // ⚠ 切り出しは**打ったまま**(全角を勝手に半角へ直して見せない)
    expect(hits[1]!.raw).toBe('０９０－１２３４－５６７８');
    expect(hits[0]!.end <= hits[1]!.start, '範囲が重なっている').toBe(true);
  });

  /**
   * 🔴 **末尾の区切りを落とす門**(変異試験 P6 が SURVIVED で教えた)。
   * ⚠ 落とさないと `telOf` が「区切りで終わる」と断るので、**押せる字にならない**
   *   ── 門が 2 つ在って、互いに救い合っていた(CLAUDE.md §3.9)。
   */
  it('🔴 番号の後ろに区切りが続いていても、番号は拾う', () => {
    expect(findPhones('代表 03-1234-5678-内線 5').map((h) => h.tel)).toEqual(['0312345678']);
    expect(findPhones('03-1234-5678-').map((h) => h.raw)).toEqual(['03-1234-5678']);
  });

  it('⚠ 1 件も無い本文では、何も返さない(空振り防止の対照群)', () => {
    expect(findPhones('今日は 2026-09-09 です。1-2-3 の順で。')).toEqual([]);
  });
});
