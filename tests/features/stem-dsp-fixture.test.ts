const near = (got: ArrayLike<number>, want: readonly number[], tol = 2e-5): void => {
  expect(got.length).toBe(want.length);
  let worst = 0;
  for (let i = 0; i < want.length; i++) worst = Math.max(worst, Math.abs(got[i]! - want[i]!));
  expect(worst, `最大の差 ${worst}`).toBeLessThan(tol);
};

describe('STFT の規約 ── numpy の既知値と一致する', () => {
  it('前提: 設定の長さ', () => {
    expect(chunkSamples(SPEC)).toBe(LEFT.length);
    expect(SPECTRUM.length).toBe(4 * SPEC.dimF * SPEC.dimT);
  });

  it('🔴 順変換: [左の実部, 左の虚部, 右の実部, 右の虚部] × 下から dimF 本 × frame', () => {
    const out = new Float32Array(4 * SPEC.dimF * SPEC.dimT);
    toModelInput(new Fft(SPEC.nFft), hannWindow(SPEC.nFft), SPEC, Float32Array.from(LEFT), 0, Float32Array.from(RIGHT), 0, 0, out);
    near(out, SPECTRUM);
    // 空振り防止: 4 つのスロットはどれも 0 ではなく、互いに違う
    const slot = (c: number): number[] => Array.from(out.subarray(c * SPEC.dimF * SPEC.dimT, (c + 1) * SPEC.dimF * SPEC.dimT));
    for (let c = 0; c < 4; c++) expect(slot(c).some((v) => Math.abs(v) > 0.05), `スロット ${c} が空`).toBe(true);
    expect(slot(0)).not.toEqual(slot(2));
    expect(slot(1)).not.toEqual(slot(3));
  });

  it('🔴 逆変換: 期待する左右の波形になる(スロットの取り違え・窓・重ね合わせの割り算の誤りで外れる)', () => {
    const l = new Float32Array(LEFT.length);
    const r = new Float32Array(LEFT.length);
    fromModelOutput(new Fft(SPEC.nFft), hannWindow(SPEC.nFft), SPEC, Float32Array.from(SPECTRUM_B), l, r);
    near(l, OUT_L);
    near(r, OUT_R);
  });

  it('🔴 窓は周期版のハン窓(対称版ではない)', () => {
    const w = hannWindow(12);
    expect(w[0]).toBe(0);
    expect(w[6]).toBeCloseTo(1, 12); // 周期版は中央(n/2)がちょうど 1
    expect(w[1]).toBeCloseTo(0.5 - 0.5 * Math.cos(Math.PI / 6), 12);
  });
});

