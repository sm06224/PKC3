/**
 * 🔴 **コメントを落とす**(TypeScript / JavaScript のソースを読む検査のため)。
 *
 * ⚠ **「在る」ことを主張する検査**でだけ使う ── 注釈が検査を満たしてしまうと、
 *   実装を消しても緑になる(CLAUDE.md §1「注釈が検査を満たす」)。
 * ⚠ 逆に「**無い**」ことを主張する検査には掛けない ── そちらは広く拾うほうが
 *   安全側(コメントで誤検知して落ちるのは、見逃すよりずっとよい)。
 *
 * ## 🔴 なぜ 1 か所に寄せたか ── 写しが **2 通りの強さ**に割れていた(#461)
 *
 * `tests/` を全数走査すると、同じ「TS のコメントを落とす」が **7 か所**あり、
 * しかも**規則が 2 通り**だった。⚠ **どちらも同じ名前**(`codeOnly` /
 * `stripComments`)なので、**強さが違うことは名前からは分からない**:
 *
 * | 版 | 規則 | `const x = 1; // aria-label` |
 * |---|---|---|
 * | **行版**(4 か所) | 行頭が `//` `*` `/*` の**行を落とす** | 🔴 **`// aria-label` が残る** |
 * | **範囲版**(3 か所) | `/* … *\/` と**行末の `//`** を落とす | ✅ `const x = 1; ` |
 *
 * 🔴 **行版では、行末の注釈が検査を満たせる。** `foo(); /* aria-label *\/ bar();`
 *   のような**行の途中の囲み注釈**も丸ごと残る(実測)。つまり
 *   **「在る」ことの主張が、注釈だけで通る** ── #250 で実際に踏んだ型である。
 *
 * 🔑 だから**強いほう(範囲版)に寄せた**。⚠ 寄せる前に
 *   **弱い版を使っていた検査 7 本 126 件を強い版で回して、1 件も落ちないこと**を
 *   確かめてある(= **注釈に頼って通っていた検査は無かった**)。
 *
 * ⚠ **YAML(`#`)と CSS(`/* *\/`)は別の言語なので、ここへ寄せない。**
 *   CSS は `tests/helpers/css-blocks.ts` の `stripComments` が正本である。
 */

/**
 * TS / JS のコメントを落とす。
 *
 * ⚠ `://` は残す(`https://…` を注釈と読まないため)。
 * ⚠ 文字列リテラルの中の `//` も落ちる ── **落としすぎる側**の誤差であり、
 *   「在る」ことの主張では**安全側**である(通りにくくなるだけ)。
 */
export function codeOnly(src: string): string {
  return src.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
}
