/**
 * 🔴 **コメント行を落とす**(TypeScript / JavaScript のソースを読む検査のため)。
 *
 * ⚠ **「在る」ことを主張する検査**でだけ使う ── 注釈が検査を満たしてしまうと、
 *   実装を消しても緑になる(CLAUDE.md §1「注釈が検査を満たす」)。
 * ⚠ 逆に「**無い**」ことを主張する検査には掛けない ── そちらは広く拾うほうが
 *   安全側(コメントで誤検知して落ちるのは、見逃すよりずっとよい)。
 *
 * 🔑 **置き場をここにしたのは、写しが増えていたからである**(#454 で数えた)──
 *   `tests/` を全数走査すると、同じことをする処理が **20 か所**あり、しかも
 *   **規則が 5 通りに割れている**(`/*` を落とす版・落とさない版・行末まで落とす版…)。
 *   ⚠ **落とす規則が違うと、どのコメントが検査を満たすかが変わる** ──
 *   落とさない側は「実装を消しても緑」になりうる。
 *   ⚠ 既存の写しを寄せるのは別の変更なので **#461** に分けた ── **新しく書くときは
 *   ここへ足す**(21 本目を書かない)。
 */
export function codeOnly(src: string): string {
  return src
    .split('\n')
    .filter((l) => !/^\s*(\/\/|\*|\/\*)/.test(l))
    .join('\n');
}
